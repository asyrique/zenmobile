#!/usr/bin/env bash
# Regenerates the UniFFI Swift bindings in core/swift/ZenCore from a built
# libzen_core. Bindings are generated in library mode, so every component
# linked into zen-core (fxa-client, tabs, zen-spaces, ...) is included.
#
# Usage: scripts/generate-swift-bindings.sh [path/to/libzen_core.{so,dylib,a}]
# Default: core/target/debug/libzen_core.so (or .dylib on macOS), built first.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
CORE="$ROOT/core"
PKG="$CORE/swift/ZenCore"

if [[ $# -ge 1 ]]; then
  LIB="$1"
else
  case "$(uname)" in
    Darwin) LIB="$CORE/target/debug/libzen_core.dylib" ;;
    *) LIB="$CORE/target/debug/libzen_core.so" ;;
  esac
  (cd "$CORE" && cargo build -p zen-core)
fi

OUT="$(mktemp -d)"
trap 'rm -rf "$OUT"' EXIT
(cd "$CORE" && cargo run -q -p uniffi-bindgen -- generate --language swift --out-dir "$OUT" "$LIB")

GEN_SWIFT="$PKG/Sources/ZenCore/Generated"
GEN_FFI="$PKG/Sources/ZenCoreFFI/include"
rm -rf "$GEN_SWIFT" && mkdir -p "$GEN_SWIFT"
find "$GEN_FFI" -name '*.h' -delete
cp "$OUT"/*.swift "$GEN_SWIFT/"
cp "$OUT"/*.h "$GEN_FFI/"

# One modulemap declaring every FFI module. The generated Swift does
# `#if canImport(<module>) import <module>`, so names must match what each
# crate's uniffi.toml chose: application-services puts all its components in
# a single `MozillaRustComponents` module, our crates use `<crate>FFI`.
# Headers are grouped per module name. Apple-only `use "Darwin"` lines are
# dropped; they only matter for -fmodules-decluse, and break Linux/Android.
python3 - "$OUT" "$GEN_FFI/module.modulemap" <<'PY'
import collections, pathlib, re, sys
out, dest = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
modules = collections.OrderedDict()
for path in sorted(out.glob("*.modulemap")):
    text = path.read_text()
    name = re.search(r"module\s+(\w+)\s*\{", text).group(1)
    modules.setdefault(name, []).extend(re.findall(r'header\s+"([^"]+)"', text))
lines = ["// Generated by scripts/generate-swift-bindings.sh. Do not edit."]
for name, headers in modules.items():
    lines.append(f"module {name} {{")
    lines += [f'    header "{h}"' for h in headers]
    lines += ["    export *", "}", ""]
dest.write_text("\n".join(lines))
PY

echo "Generated $(ls "$GEN_SWIFT" | wc -l) Swift files into $GEN_SWIFT"
